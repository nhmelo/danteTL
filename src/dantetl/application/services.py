"""Narrow view ports. These expose commands and immutable values, never resource owners."""

from pathlib import Path
from typing import Protocol

from dantetl.application.model_values import ModelFile
from dantetl.runtime.hardware_values import HardwareStatus
from dantetl.runtime.setup_values import RuntimeStatus, SetupJob, SetupLane, SetupReview
from dantetl.runtime.values import RuntimeProfile
from dantetl.translation.cache_values import CacheView
from dantetl.translation.cloud.state import CloudDraft, CloudSnapshot
from dantetl.translation.cloud.values import CloudProfile, CloudUsage
from dantetl.translation.models.values import ImportedModel, ProbeResult
from dantetl.translation.ollama.values import OllamaModel, OllamaSnapshot


class OllamaCommands(Protocol):
    def begin(self) -> None: ...
    def snapshot(self) -> OllamaSnapshot: ...
    def find(self, address: str) -> None: ...
    def save(self, server: str, models: tuple[OllamaModel, ...]) -> None: ...
    def discard(self) -> None: ...


class CacheCommands(Protocol):
    def snapshot(self) -> CacheView: ...
    def refresh(self) -> None: ...
    def clear(self, game: str | None) -> None: ...


class CloudCommands(Protocol):
    def snapshot(self) -> CloudSnapshot: ...
    def usage(self, key: str) -> CloudUsage: ...
    def take_browser(self) -> str: ...
    def take_welcome(self) -> str: ...
    def acknowledge_welcome(self, account: str) -> None: ...
    def discard_draft(self) -> None: ...
    def cancel(self) -> None: ...
    def save(self, draft: CloudDraft) -> None: ...
    def refresh_models(self, draft: CloudDraft) -> None: ...
    @property
    def test_sample(self) -> str: ...
    def test(self, draft: CloudDraft) -> None: ...
    def remove(self, profile: CloudProfile) -> None: ...
    def forget_key(self, key: str) -> None: ...
    def sign_in(self, selected: str) -> None: ...
    def sign_out(self, account: str) -> None: ...
    def refresh_account(self, account: str) -> None: ...


class SetupCommands(Protocol):
    @property
    def inventory_revision(self) -> int: ...
    @property
    def profiles(self) -> tuple[RuntimeProfile, ...]: ...

    @property
    def files(self) -> tuple[ModelFile, ...]: ...
    @property
    def guide_models(self) -> tuple[ModelFile, ...]: ...
    def job(self, lane: SetupLane) -> SetupJob: ...
    @property
    def busy(self) -> bool: ...
    @property
    def problem(self) -> str: ...
    def download(self, key: str) -> bool: ...
    def remove(self, key: str) -> bool: ...
    def begin_import(self, expected: ImportedModel | None = None) -> bool: ...
    def invalidate_import(self) -> None: ...
    @property
    def probe_result(self) -> ProbeResult | None: ...
    def test_import(self, path: str, profile: str) -> bool: ...
    def save_import(self, name: str) -> bool: ...
    @property
    def runtime(self) -> RuntimeStatus: ...
    def detect_runtime(self) -> bool: ...
    def install_runtime(self, key: str) -> bool: ...
    def use_next_launch(self, key: str) -> bool: ...
    def review(self, model_key: str, runtime_key: str, hardware: HardwareStatus) -> SetupReview: ...
    def review_ocr(self, hardware: HardwareStatus, *, cuda: bool) -> SetupReview: ...
    def start_review(self, token: int) -> bool: ...
    @property
    def guide_target(self) -> Path | None: ...
    @property
    def reviewed(self) -> SetupReview | None: ...
    def acknowledge_review(self, token: int) -> str | None: ...
    def cancel(self, lane: SetupLane) -> None: ...
